def train_model(model, train_loader, test_loader, optimizer, num_epochs=25, device='cuda'):
    """
    Train the model and track both training and testing metrics
    """
    import time
    start_time = time.time()

    # Track metrics
    train_losses = []
    test_losses = []
    train_accuracies = []
    test_accuracies = []

    print("Starting training...")

    for epoch in range(num_epochs):
        # Training phase
        model.train()
        epoch_loss = 0.0
        batch_count = 0

        print(f"Epoch {epoch+1}/{num_epochs}")
        progress_bar = tqdm(train_loader, desc="Training")

        for images, targets in progress_bar:
            images = list(img.to(device) for img in images)
            targets = [{k: v.to(device) for k, v in t.items()} for t in targets]

            # Forward pass
            loss_dict = model(images, targets)
            losses = sum(loss for loss in loss_dict.values())

            # Backward pass
            optimizer.zero_grad()
            losses.backward()
            optimizer.step()

            # Track metrics
            epoch_loss += losses.item()
            batch_count += 1
            progress_bar.set_postfix(loss=losses.item())

        avg_epoch_loss = epoch_loss / batch_count if batch_count > 0 else 0
        train_losses.append(avg_epoch_loss)

        # Testing phase - calculate loss
        model.eval()
        test_epoch_loss = 0.0
        test_batch_count = 0

        print("Evaluating test loss...")
        with torch.no_grad():
            for images, targets in tqdm(list(itertools.islice(test_loader, min(50, len(test_loader)))), desc="Testing"):
                images = list(img.to(device) for img in images)
                targets = [{k: v.to(device) for k, v in t.items()} for t in targets]

                # Forward pass in eval mode (need to handle differently since model doesn't return loss in eval mode)
                # We'll manually compute the loss
                model.train()  # Temporarily set to train mode to get losses
                loss_dict = model(images, targets)
                test_loss = sum(loss for loss in loss_dict.values())
                model.eval()  # Set back to eval mode

                test_epoch_loss += test_loss.item()
                test_batch_count += 1

        avg_test_loss = test_epoch_loss / test_batch_count if test_batch_count > 0 else 0
        test_losses.append(avg_test_loss)

        # Calculate training accuracy (on a sample for speed)
        print("Evaluating training accuracy...")
        train_metrics = evaluate_model(model, train_loader, device, sample_size=min(20, len(train_loader)))
        train_accuracies.append(train_metrics['accuracy'])

        # Calculate test accuracy
        print("Evaluating test accuracy...")
        test_metrics = evaluate_model(model, test_loader, device, sample_size=min(50, len(test_loader)))
        test_accuracies.append(test_metrics['accuracy'])

        print(f"Epoch {epoch+1}/{num_epochs} - "
              f"Train Loss: {avg_epoch_loss:.4f}, Test Loss: {avg_test_loss:.4f}, "
              f"Train Accuracy: {train_metrics['accuracy']:.4f}, "
              f"Test Accuracy: {test_metrics['accuracy']:.4f}")

        # Save model checkpoint every 5 epochs
        if (epoch + 1) % 5 == 0:
            torch.save(model.state_dict(), f"/content/drive/MyDrive/models/faster_rcnn_epoch_{epoch+1}.pth")

    end_time = time.time()
    execution_time = end_time - start_time
    print(f"Total training time: {execution_time:.2f} seconds ({execution_time/60:.2f} minutes)")

    # Save metrics to CSV
    metrics_df = pd.DataFrame({
        'epoch': list(range(1, num_epochs + 1)),
        'train_loss': train_losses,
        'test_loss': test_losses,
        'train_accuracy': train_accuracies,
        'test_accuracy': test_accuracies,
        'execution_time': execution_time
    })
    metrics_df.to_csv('/content/drive/MyDrive/Required/fastercnn/model_history.csv', index=False)
    print("Model history saved to model_history.csv")

    # Plot training and test metrics
    plt.figure(figsize=(12, 15))

    # Plot training vs test loss
    plt.subplot(3, 1, 1)
    plt.plot(range(1, num_epochs + 1), train_losses, 'b-', label='Training Loss')
    plt.plot(range(1, num_epochs + 1), test_losses, 'r-', label='Testing Loss')
    plt.title('Training vs Testing Loss')
    plt.xlabel('Epoch')
    plt.ylabel('Loss')
    plt.legend()
    plt.grid(True)

    # Plot training vs test accuracy
    plt.subplot(3, 1, 2)
    plt.plot(range(1, num_epochs + 1), train_accuracies, 'b-', label='Training Accuracy')
    plt.plot(range(1, num_epochs + 1), test_accuracies, 'r-', label='Testing Accuracy')
    plt.title('Training vs Testing Accuracy')
    plt.xlabel('Epoch')
    plt.ylabel('Accuracy')
    plt.legend()
    plt.grid(True)

    # Plot loss vs accuracy
    plt.subplot(3, 1, 3)
    plt.plot(train_losses, train_accuracies, 'bo-', label='Training')
    plt.plot(test_losses, test_accuracies, 'ro-', label='Testing')
    plt.title('Loss vs Accuracy')
    plt.xlabel('Loss')
    plt.ylabel('Accuracy')
    plt.legend()
    plt.grid(True)

    plt.tight_layout()
    plt.savefig('/content/drive/MyDrive/Required/fastercnn/training_metrics.png')
    plt.show()

    return model, {
        'train_losses': train_losses,
        'test_losses': test_losses,
        'train_accuracies': train_accuracies,
        'test_accuracies': test_accuracies,
        'execution_time': execution_time
    }


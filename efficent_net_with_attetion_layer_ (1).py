class LunarDataset(Dataset):
    def __init__(self, csv_file, img_dir, transform=None):
        try:
            self.annotations = pd.read_csv(csv_file)
        except Exception as e:
            raise ValueError(f"Failed to load CSV file {csv_file}: {e}")

        self.img_dir = img_dir
        self.transform = transform
        self.classes = ['Crater', 'Boulder']
        self.class_to_idx = {cls: idx + 1 for idx, cls in enumerate(self.classes)}  # Map to 1, 2 (0 is background)

        # Get unique image filenames and filter out images with no valid annotations
        self.image_names = self.annotations['filename'].unique()
        self.valid_images = []
        for img_name in self.image_names:
            img_annotations = self.annotations[self.annotations['filename'] == img_name]
            valid_annotations = img_annotations[img_annotations['class'].isin(self.classes)]
            has_valid_box = False
            for _, row in valid_annotations.iterrows():
                xmin, ymin, xmax, ymax = row[['xmin', 'ymin', 'xmax', 'ymax']]
                if (isinstance(xmin, (int, float)) and isinstance(ymin, (int, float)) and
                        isinstance(xmax, (int, float)) and isinstance(ymax, (int, float)) and
                        xmin < xmax and ymin < ymax):
                    has_valid_box = True
                    break
            if has_valid_box:
                img_path = os.path.join(self.img_dir, img_name)
                if os.path.exists(img_path):
                    self.valid_images.append(img_name)
                else:
                    print(f"Skipping {img_name}: Image file missing")
            else:
                print(f"Skipping {img_name}: No valid Crater or Boulder annotations")

        if not self.valid_images:
            raise ValueError(f"No valid images with Crater or Boulder annotations in {csv_file}")

        print(f"Dataset {csv_file}: {len(self.valid_images)} valid images")

    def __len__(self):
        return len(self.valid_images)

    def __getitem__(self, idx):
        img_name = self.valid_images[idx]
        img_path = os.path.join(self.img_dir, img_name)
        try:
            image = Image.open(img_path).convert('RGB')
        except Exception as e:
            print(f"Error loading image {img_name}: {e}")
            image = Image.new('RGB', (640, 640), color='black')
            target = {
                'boxes': torch.zeros((0, 4), dtype=torch.float32),
                'labels': torch.zeros(0, dtype=torch.int64),
                'image_id': torch.tensor([idx]),
                'area': torch.tensor([]),
                'iscrowd': torch.zeros((0,), dtype=torch.int64)
            }
            if self.transform:
                image = self.transform(image)
            return image, target, img_name

        img_annotations = self.annotations[self.annotations['filename'] == img_name]
        boxes = []
        labels = []
        for _, row in img_annotations.iterrows():
            class_name = row['class']
            if class_name in self.class_to_idx:
                xmin, ymin, xmax, ymax = row[['xmin', 'ymin', 'xmax', 'ymax']]
                if (isinstance(xmin, (int, float)) and isinstance(ymin, (int, float)) and
                        isinstance(xmax, (int, float)) and isinstance(ymax, (int, float)) and
                        xmin < xmax and ymin < ymax):
                    boxes.append([xmin, ymin, xmax, ymax])
                    labels.append(self.class_to_idx[class_name])
                else:
                    print(f"Invalid box for {img_name}, class {class_name}: {xmin, ymin, xmax, ymax}")

        boxes = torch.as_tensor(boxes, dtype=torch.float32)
        labels = torch.as_tensor(labels, dtype=torch.int64)

        if len(boxes) == 0:
            print(f"Warning: Empty target for {img_name} after processing")
            boxes = torch.zeros((0, 4), dtype=torch.float32)
            labels = torch.zeros(0, dtype=torch.int64)

        target = {
            'boxes': boxes,
            'labels': labels,
            'image_id': torch.tensor([idx]),
            'area': (boxes[:, 3] - boxes[:, 1]) * (boxes[:, 2] - boxes[:, 0]) if len(boxes) > 0 else torch.tensor([]),
            'iscrowd': torch.zeros((len(boxes),), dtype=torch.int64)
        }

        if self.transform:
            image = self.transform(image)

        return image, target, img_name


def visualize_predictions(model, data_loader, class_names, device, score_threshold=0.5, max_images=5, save_dir=''):
    """Visualize model predictions on images from the data loader"""
    model.eval()
    results = []

    with torch.no_grad():
        for i, (images, targets, img_names) in enumerate(data_loader):
            if i >= max_images:
                break

            images_list = list(img.to(device) for img in images)
            targets_list = [{k: v.to(device) for k, v in t.items()} for t in targets]

            # Run inference
            outputs = model(images_list)

            # Store results
            for j, (img, target, prediction, img_name) in enumerate(zip(images_list, targets_list, outputs, img_names)):
                results.append({
                    'image': img.cpu(),
                    'target': target,
                    'prediction': prediction,
                    'image_name': img_name
                })

    # Visualize results
    for idx, result in enumerate(results):
        img = result['image'].permute(1, 2, 0).numpy()
        img = img * np.array([0.229, 0.224, 0.225]) + np.array([0.485, 0.456, 0.406])
        img = np.clip(img, 0, 1)

        # Create figure with 2 subplots (ground truth and predictions)
        fig, (ax1, ax2) = plt.subplots(1, 2, figsize=(20, 10))

        # Ground Truth
        ax1.imshow(img)
        gt_boxes = result['target']['boxes'].cpu().numpy()
        gt_labels = result['target']['labels'].cpu().numpy()

        for box, label in zip(gt_boxes, gt_labels):
            x1, y1, x2, y2 = box
            rect = patches.Rectangle((x1, y1), x2-x1, y2-y1, linewidth=2, edgecolor='g', facecolor='none')
            ax1.add_patch(rect)
            ax1.text(x1, y1-10, class_names[label-1], color='white', fontsize=12,
                    bbox=dict(facecolor='g', alpha=0.7))

        ax1.set_title(f"Ground Truth - {result['image_name']}")
        ax1.axis('off')

        # Predictions
        ax2.imshow(img)
        pred_boxes = result['prediction']['boxes'].cpu().numpy()
        pred_labels = result['prediction']['labels'].cpu().numpy()
        pred_scores = result['prediction']['scores'].cpu().numpy()

        # Filter by score threshold
        valid_indices = pred_scores >= score_threshold
        filtered_boxes = pred_boxes[valid_indices]
        filtered_labels = pred_labels[valid_indices]
        filtered_scores = pred_scores[valid_indices]

        for box, label, score in zip(filtered_boxes, filtered_labels, filtered_scores):
            x1, y1, x2, y2 = box
            rect = patches.Rectangle((x1, y1), x2-x1, y2-y1, linewidth=2, edgecolor='r', facecolor='none')
            ax2.add_patch(rect)
            ax2.text(x1, y1-10, f"{class_names[label-1]}: {score:.2f}", color='white', fontsize=12,
                    bbox=dict(facecolor='r', alpha=0.7))

        ax2.set_title(f"Predictions (score ≥ {score_threshold}) - {result['image_name']}")
        ax2.axis('off')

        plt.tight_layout()
        save_path = os.path.join(save_dir, f"prediction_visualization_{idx}.png")
        plt.savefig(save_path)
        plt.close()

        # Print detection metrics for this image
        matched_preds, matched_labels = match_predictions_to_targets(
            [result['prediction']], [result['target']])

        if matched_labels:
            acc = sum(p == t for p, t in zip(matched_preds, matched_labels)) / len(matched_labels)
            print(f"Image {idx+1} ({result['image_name']}) - Detection Accuracy: {acc:.4f}")
        else:
            print(f"Image {idx+1} ({result['image_name']}) - No matched predictions")

        # Print counts of each class
        pred_class_counts = {
            class_name: sum(filtered_labels == class_idx+1)
            for class_idx, class_name in enumerate(class_names)
        }
        gt_class_counts = {
            class_name: sum(gt_labels == class_idx+1)
            for class_idx, class_name in enumerate(class_names)
        }

        print(f"Ground Truth: {gt_class_counts}")
        print(f"Predictions: {pred_class_counts}")
        print("-" * 50)


def calculate_confusion_matrix(model, dataloader, device):
    """Calculate and visualize confusion matrix"""
    model.eval()
    all_preds = []
    all_labels = []

    with torch.no_grad():
        for images, targets, _ in dataloader:
            for i in range(len(images)):
                # Skip images with no annotations
                if len(targets[i]['labels']) == 0:
                    continue

                image = images[i].unsqueeze(0).to(device)
                label = targets[i]['labels'][0].item()

                class_logits, _ = model(image)
                pred = class_logits.argmax(1).item()

                all_preds.append(pred)
                all_labels.append(label)

    if len(all_preds) > 0:
        # Generate confusion matrix
        cm = confusion_matrix(all_labels, all_preds)

        # Plot confusion matrix
        plt.figure(figsize=(8, 6))
        plt.imshow(cm, interpolation='nearest', cmap=plt.cm.Blues)
        plt.title('Confusion Matrix')
        plt.colorbar()

        classes = ['Crater', 'Boulder']
        tick_marks = np.arange(len(classes))
        plt.xticks(tick_marks, classes, rotation=45)
        plt.yticks(tick_marks, classes)

        # Add text annotations
        thresh = cm.max() / 2
        for i in range(cm.shape[0]):
            for j in range(cm.shape[1]):
                plt.text(j, i, format(cm[i, j], 'd'),
                        horizontalalignment="center",
                        color="white" if cm[i, j] > thresh else "black")

        plt.ylabel('True label')
        plt.xlabel('Predicted label')
        plt.tight_layout()
        plt.savefig(os.path.join(RESULTS_PATH, 'confusion_matrix.png'))
        plt.show()

        return cm

    return None

def plot_roc_curve(model, dataloader, device):
    """Plot ROC curve for the model"""
    model.eval()
    all_scores = []
    all_labels = []

    with torch.no_grad():
        for images, targets, _ in dataloader:
            for i in range(len(images)):
                # Skip images with no annotations
                if len(targets[i]['labels']) == 0:
                    continue

                image = images[i].unsqueeze(0).to(device)
                label = targets[i]['labels'][0].item()

                class_logits, _ = model(image)
                score = torch.softmax(class_logits, dim=1)[0][1].item()  # Probability of class 1 (Boulder)

                all_scores.append(score)
                all_labels.append(label)

    if len(all_scores) > 0 and len(np.unique(all_labels)) > 1:
        # Calculate ROC curve
        fpr, tpr, _ = roc_curve(all_labels, all_scores)
        roc_auc = roc_auc_score(all_labels, all_scores)

        # Plot ROC curve
        plt.figure(figsize=(8, 6))
        plt.plot(fpr, tpr, color='darkorange', lw=2, label=f'ROC curve (area = {roc_auc:.2f})')
        plt.plot([0, 1], [0, 1], color='navy', lw=2, linestyle='--')
        plt.xlim([0.0, 1.0])
        plt.ylim([0.0, 1.05])
        plt.xlabel('False Positive Rate')
        plt.ylabel('True Positive Rate')
        plt.title('Receiver Operating Characteristic (ROC) Curve')
        plt.legend(loc="lower right")
        plt.savefig(os.path.join(RESULTS_PATH, 'roc_curve.png'))
        plt.show()

        return roc_auc

    return None

def main():
    # Set random seed for reproducibility
    torch.manual_seed(42)
    np.random.seed(42)

    # Check if CUDA is available
    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    print(f"Using device: {device}")

    # Create datasets
    train_ds = CraterBoulderDataset(os.path.join(BASE_PATH, 'train'), transform=get_transform(train=True))
    valid_ds = CraterBoulderDataset(os.path.join(BASE_PATH, 'valid'), transform=get_transform(train=False))
    test_ds = CraterBoulderDataset(os.path.join(BASE_PATH, 'test'), transform=get_transform(train=False))

    print(f"Train dataset size: {len(train_ds)}")
    print(f"Validation dataset size: {len(valid_ds)}")
    print(f"Test dataset size: {len(test_ds)}")

    # Create data loaders
    train_loader = DataLoader(train_ds, batch_size=4, shuffle=True, collate_fn=collate_fn)
    valid_loader = DataLoader(valid_ds, batch_size=4, shuffle=False, collate_fn=collate_fn)
    test_loader = DataLoader(test_ds, batch_size=4, shuffle=False, collate_fn=collate_fn)

    # Initialize model
    model = DetectionModel(num_classes=2).to(device)

    # Define optimizer and loss functions
    optimizer = torch.optim.Adam(model.parameters(), lr=1e-4)
    criterion_cls = nn.CrossEntropyLoss()
    criterion_bbox = nn.MSELoss()

    # Initialize history dictionary
    history = {
        'train_loss': [], 'train_cls_loss': [], 'train_bbox_loss': [],
        'train_accuracy': [], 'train_precision': [], 'train_recall': [], 'train_f1': [],
        'val_loss': [], 'val_cls_loss': [], 'val_bbox_loss': [],
        'val_accuracy': [], 'val_precision': [], 'val_recall': [], 'val_f1': [], 'val_auc': [],
        'epoch_time': []
    }

    # Training start time
    total_start_time = time.time()

    # Number of epochs
    num_epochs = 15

    # Training loop
    for epoch in range(num_epochs):
        # Train
        train_loss, train_acc, train_prec, train_rec, train_f1 = train_model(
            model, train_loader, optimizer, criterion_cls, criterion_bbox, device, epoch, history
        )

        # Validate
        val_loss, val_acc, val_prec, val_rec, val_f1, val_auc = validate_model(
            model, valid_loader, criterion_cls, criterion_bbox, device, epoch, history
        )

    # Total training time
    total_time = time.time() - total_start_time
    print(f"Total training time: {total_time:.2f} seconds")

    # Save training history
    save_history_to_csv(history, os.path.join(RESULTS_PATH, 'training_history.csv'))

    # Save execution time to CSV
    with open(os.path.join(RESULTS_PATH, 'execution_time.csv'), 'w', newline='') as f:
        writer = csv.writer(f)
        writer.writerow(['Total Training Time (s)', 'Average Epoch Time (s)'])
        writer.writerow([total_time, sum(history['epoch_time'])/len(history['epoch_time'])])

    # Plot and save metrics
    plot_metrics(history, save_path=os.path.join(RESULTS_PATH, 'training_metrics.png'))

    # Save model
    torch.save({
        'model_state_dict': model.state_dict(),
        'optimizer_state_dict': optimizer.state_dict(),
        'history': history,
    }, os.path.join(RESULTS_PATH, 'model_checkpoint.pth'))

    # Evaluate on test set
    test_loss, test_acc, test_prec, test_rec, test_f1, test_auc = validate_model(
        model, test_loader, criterion_cls, criterion_bbox, device, num_epochs, history
    )

    # Save test metrics to CSV
    with open(os.path.join(RESULTS_PATH, 'test_metrics.csv'), 'w', newline='') as f:
        writer = csv.writer(f)
        writer.writerow(['Accuracy', 'Precision', 'Recall', 'F1 Score', 'AUC'])
        writer.writerow([test_acc, test_prec, test_rec, test_f1, test_auc])

    # Visualize test predictions
    visualize_dir = os.path.join(RESULTS_PATH, 'visualizations')
    os.makedirs(visualize_dir, exist_ok=True)
    visualize_predictions(model, test_ds, device, num_samples=10, save_dir=visualize_dir)

    # Generate confusion matrix
    calculate_confusion_matrix(model, test_loader, device)

    # Plot ROC curve
    plot_roc_curve(model, test_loader, device)

    print(f"All results saved to {RESULTS_PATH}")

if __name__ == "__main__":
    main()
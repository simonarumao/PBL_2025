class GumbelSigmoid(nn.Module):
    """Gumbel Sigmoid activation for differentiable discrete sampling"""
    def __init__(self, temperature=1.0):
        super().__init__()
        self.temperature = temperature

    def forward(self, logits):
        noise = torch.rand_like(logits)
        noise = -torch.log(-torch.log(noise + 1e-20) + 1e-20)
        return torch.sigmoid((logits + noise) / self.temperature)

class MultiScaleAttention(nn.Module):
    """Multi-Scale Attention module for focusing on relevant features at different scales"""
    def __init__(self, num_slots, feature_dim, attn_temperature=0.5, gumbel_temperature=0.5, dropout_rate=0.1):
        super(MultiScaleAttention, self).__init__()
        self.num_slots = num_slots
        self.feature_dim = feature_dim
        self.attn_temperature = attn_temperature
        self.dropout_rate = dropout_rate

        # Attention components
        self.query_proj = nn.Linear(feature_dim, feature_dim)
        # Change here: The in_channels must match the output channels of the fpn_convs layers
        self.key_value_projs = nn.ModuleList([nn.Conv2d(feature_dim, 2 * feature_dim, kernel_size=1)
                                             for _ in range(4)])

        # Learnable scale embeddings
        self.scale_embeddings = nn.ParameterList([
            nn.Parameter(torch.randn(feature_dim)) for _ in range(4)
        ])

        # Scale fusion weights
        self.scale_fusion_weights = nn.ParameterList([
            nn.Parameter(torch.randn(feature_dim, feature_dim)) for _ in range(4)
        ])

        self.gumbel_sigmoid = GumbelSigmoid(temperature=gumbel_temperature)
        self.dropout = nn.Dropout(dropout_rate)

        # MLP for slot updates
        self.mlp = nn.Sequential(
            nn.Linear(feature_dim, feature_dim * 2),
            nn.ReLU(),
            nn.Linear(feature_dim * 2, feature_dim)
        )

        # Mask decoder for visualization
        self.mask_decoder = nn.Linear(feature_dim, 128 * 128)
        self.layer_norm = nn.LayerNorm(feature_dim)

    def forward(self, features, slots):
        """
        Args:
            features: List of feature maps from different scales
            slots: [num_slots, feature_dim] attention slots
        Returns:
            Updated slots and attention masks
        """
        all_attended = []
        slots_norm = self.layer_norm(slots)
        queries = self.query_proj(slots_norm)  # [num_slots, feature_dim]

        for idx, feature_map in enumerate(features):
            B, C, H, W = feature_map.shape
            # Project feature map to keys and values
            proj = self.key_value_projs[idx](feature_map)  # [B, 2*feature_dim, H, W]
            keys, values = torch.split(proj, self.feature_dim, dim=1)

            # Reshape for attention
            keys = keys.permute(0, 2, 3, 1).reshape(B, H*W, self.feature_dim)  # [B, H*W, feature_dim]
            values = values.permute(0, 2, 3, 1).reshape(B, H*W, self.feature_dim)  # [B, H*W, feature_dim]

            # Scale-specific gating
            logits = self.query_proj(queries) + self.scale_embeddings[idx]
            gates = self.gumbel_sigmoid(logits)  # [num_slots, feature_dim]

            # Compute attention
            queries = self.query_proj(queries) * gates
            queries = queries + self.scale_embeddings[idx]

            # Compute attention
            attn_logits = torch.matmul(queries, keys.transpose(-2, -1))  # [num_slots, H*W]
            attn_logits = attn_logits / (self.attn_temperature * torch.sqrt(torch.tensor(self.feature_dim, dtype=torch.float32)))
            attn_weights = F.softmax(attn_logits, dim=-1)

            # Apply dropout (gating is already applied)
            attn_weights = self.dropout(attn_weights)

            # Attend to values
            attended = torch.matmul(attn_weights, values)  # [num_slots, feature_dim]

            # Scale-specific fusion
            fused = torch.matmul(attended, self.scale_fusion_weights[idx])
            all_attended.append(fused)

        # Combine attended features from all scales
        fused = torch.stack(all_attended).sum(dim=0)
        fused_norm = self.layer_norm(fused)

        # Update slots with MLP
        updated_slots = slots + self.mlp(fused_norm)

        # Decode masks for visualization (optional, can be used during training)
        masks = self.mask_decoder(updated_slots)
        masks = masks.reshape(-1, 128, 128)
        masks = torch.sigmoid(masks)

        return updated_slots, masks

class EfficientNetWithAttention(nn.Module):
    def __init__(self, num_slots=10, feature_dim=256):
        super(EfficientNetWithAttention, self).__init__()
        # Load EfficientNet-B3 backbone
        backbone = efficientnet_b3(weights=EfficientNet_B3_Weights.IMAGENET1K_V1)
        features = backbone.features

        # Create feature extraction layers
        self.layer1 = nn.Sequential(*features[:3])   # 32 channels
        self.layer2 = nn.Sequential(*features[3:5])  # 96 channels
        self.layer3 = nn.Sequential(*features[5:7])  # 232 channels
        self.layer4 = nn.Sequential(*features[7:9])  # 1536 channels

        # Initialize attention slots
        self.num_slots = num_slots
        self.feature_dim = feature_dim
        self.slots = nn.Parameter(torch.randn(num_slots, feature_dim))

        # Multi-scale attention module
        self.attention = MultiScaleAttention(
            num_slots=num_slots,
            feature_dim=feature_dim,
            attn_temperature=0.5,
            gumbel_temperature=0.5,
            dropout_rate=0.1
        )

        # FPN layers
        self.fpn_convs = nn.ModuleList([
            nn.Conv2d(32, feature_dim, kernel_size=1),
            nn.Conv2d(96, feature_dim, kernel_size=1),
            nn.Conv2d(232, feature_dim, kernel_size=1),
            nn.Conv2d(1536, feature_dim, kernel_size=1)
        ])

    def forward(self, x):
        # Extract features at different scales
        x1 = self.layer1(x)  # 32 channels
        x2 = self.layer2(x1)  # 96 channels
        x3 = self.layer3(x2)  # 232 channels
        x4 = self.layer4(x3)  # 1536 channels

        # Project features to common dimension
        p1 = self.fpn_convs[0](x1)
        p2 = self.fpn_convs[1](x2)
        p3 = self.fpn_convs[2](x3)
        p4 = self.fpn_convs[3](x4)

        # Apply attention to learn important features
        features = [p1, p2, p3, p4]
        updated_slots, attention_masks = self.attention(features, self.slots)

        # Return as dictionary for FPN
        # Return the features with correct keys for FasterRCNN
        return {
            '0': p1,  # Output from layer1
            '1': p2,  # Output from layer2
            '2': p3,  # Output from layer3
            '3': p4   # Output from layer4
        }

class AttentionEnhancedFPN(nn.Module):
    def __init__(self, backbone, in_channels_list, out_channels):
        super(AttentionEnhancedFPN, self).__init__()
        self.backbone = backbone
        self.out_channels = out_channels  # This is needed for FasterRCNN to work

        # Feature Pyramid Network (FPN)
        self.inner_blocks = nn.ModuleList()
        self.layer_blocks = nn.ModuleList()

        for in_channels in in_channels_list:
            self.inner_blocks.append(nn.Conv2d(in_channels, out_channels, 1))
            self.layer_blocks.append(nn.Conv2d(out_channels, out_channels, 3, padding=1))

        # Extra layer for highest level
        self.extra_blocks = nn.MaxPool2d(1, stride=2)

    def forward(self, x):
        # Get multi-scale features from the backbone
        features = self.backbone(x)

        # Apply FPN
        results = []
        last_inner = self.inner_blocks[-1](features['3'])
        results.append(self.layer_blocks[-1](last_inner))

        for idx in range(len(self.inner_blocks)-2, -1, -1):
            inner_lateral = self.inner_blocks[idx](features[str(idx)])

            # Upsample and add
            feat_shape = inner_lateral.shape[-2:]
            inner_top_down = F.interpolate(last_inner, size=feat_shape, mode="nearest")
            last_inner = inner_lateral + inner_top_down
            results.insert(0, self.layer_blocks[idx](last_inner))

        # Add extra layer (P6)
        results.append(self.extra_blocks(results[-1]))

        # Named results for detector
        names = ['p2', 'p3', 'p4', 'p5', 'p6']
        return {name: result for name, result in zip(names, results)}


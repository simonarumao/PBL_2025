def get_transform(train=True):
    if train:
        return A.Compose([
            A.Resize(224, 224),
            A.HorizontalFlip(p=0.5),
            A.RandomBrightnessContrast(p=0.2),
            A.Normalize(mean=(0.485, 0.456, 0.406),  # ImageNet means
                        std=(0.229, 0.224, 0.225)),
            ToTensorV2()
        ], bbox_params=A.BboxParams(format='pascal_voc', label_fields=['class_labels']))
    else:
        return A.Compose([
            A.Resize(224, 224),
            A.Normalize(mean=(0.485, 0.456, 0.406),
                        std=(0.229, 0.224, 0.225)),
            ToTensorV2()
        ], bbox_params=A.BboxParams(format='pascal_voc', label_fields=['class_labels']))

class CraterBoulderDataset(Dataset):
    def __init__(self, folder_path, transform=None):
        self.folder_path = folder_path
        self.data = pd.read_csv(os.path.join(folder_path, "_annotations.csv"))
        self.transform = transform
        # Filter for images that have at least one 'Crater' or 'Boulder' annotation
        self.image_files = self.data[self.data['class'].isin(['Crater', 'Boulder'])]['filename'].unique()

    def __len__(self):
        return len(self.image_files)

    def __getitem__(self, idx):
        filename = self.image_files[idx]
        img_path = os.path.join(self.folder_path, filename)

        image = cv2.imread(img_path)
        image = cv2.cvtColor(image, cv2.COLOR_BGR2RGB)

        # Get all records for the current image
        records = self.data[self.data['filename'] == filename]

        # Filter records for 'Crater' and 'Boulder' for boxes and labels
        crater_boulder_records = records[records['class'].isin(['Crater', 'Boulder'])]

        # Check if any 'Crater' or 'Boulder' boxes are found for this image
        if len(crater_boulder_records) == 0:
            # If no boxes, return an empty tensor for boxes and labels
            boxes = np.empty((0, 4), dtype=np.float32)
            labels = np.empty((0,), dtype=np.int64)
        else:
            boxes = crater_boulder_records[['xmin', 'ymin', 'xmax', 'ymax']].values
            # Map 'Crater' to 0 and 'Boulder' to 1
            labels = crater_boulder_records['class'].map({'Crater': 0, 'Boulder': 1}).values

        if self.transform:
            transformed = self.transform(image=image, bboxes=boxes, class_labels=labels)
            image = transformed['image']
            boxes = transformed['bboxes']
            labels = transformed['class_labels']

        target = {
            'boxes': torch.tensor(boxes, dtype=torch.float32) if len(boxes) > 0 else torch.zeros((0, 4), dtype=torch.float32),
            'labels': torch.tensor(labels, dtype=torch.long) if len(labels) > 0 else torch.zeros((0,), dtype=torch.long)
        }

        return image, target, filename  # Added filename for visualization purposes

class DetectionModel(nn.Module):
    def __init__(self, num_classes=2):
        super(DetectionModel, self).__init__()
        resnet = models.resnet50(weights='IMAGENET1K_V1')
        self.backbone = nn.Sequential(*list(resnet.children())[:-2])
        self.pool = nn.AdaptiveAvgPool2d((1, 1))
        self.classifier = nn.Linear(2048, num_classes)
        self.bbox_regressor = nn.Linear(2048, 4)

    def forward(self, x):
        x = self.backbone(x)
        x = self.pool(x)
        x = x.view(x.size(0), -1)
        class_logits = self.classifier(x)
        bbox_coords = self.bbox_regressor(x)
        return class_logits, bbox_coords

def collate_fn(batch):
    images = []
    targets = []
    filenames = []
    for img, target, filename in batch:
        images.append(img)
        targets.append(target)
        filenames.append(filename)
    return images, targets, filenames

def train_model(model, dataloader, optimizer, criterion_cls, criterion_bbox, device, epoch, history):
    model.train()
    total_loss = 0
    cls_loss_total = 0
    bbox_loss_total = 0
    correct, total = 0, 0

    all_preds = []
    all_labels = []

    epoch_start = time.time()

    for images, targets, _ in dataloader:
        optimizer.zero_grad()

        batch_loss = 0
        batch_cls_loss = 0
        batch_bbox_loss = 0
        batch_correct = 0

        for i in range(len(images)):
            image = images[i].unsqueeze(0).to(device)
            target = targets[i]

            # Skip images with no annotations
            if len(target['labels']) == 0:
                continue

            labels = target['labels'].to(device)
            boxes = target['boxes'].to(device)

            # Use the first object for simplicity
            label = labels[0]
            box = boxes[0]

            class_logits, bbox_preds = model(image)

            loss_cls = criterion_cls(class_logits, label.unsqueeze(0))
            loss_bbox = criterion_bbox(bbox_preds, box.unsqueeze(0))
            loss = loss_cls + loss_bbox
            loss.backward()

            _, pred = torch.max(class_logits, 1)

            all_preds.append(pred.item())
            all_labels.append(label.item())

            batch_correct += (pred == label.unsqueeze(0)).sum().item()
            batch_loss += loss.item()
            batch_cls_loss += loss_cls.item()
            batch_bbox_loss += loss_bbox.item()

        optimizer.step()
        total_loss += batch_loss / len(images)
        cls_loss_total += batch_cls_loss / len(images)
        bbox_loss_total += batch_bbox_loss / len(images)
        correct += batch_correct
        total += len(images)

    epoch_time = time.time() - epoch_start

    # Calculate metrics
    acc = correct / total if total > 0 else 0

    if len(all_preds) > 0 and len(all_labels) > 0:
        all_preds = np.array(all_preds)
        all_labels = np.array(all_labels)
        precision, recall, f1, _ = precision_recall_fscore_support(all_labels, all_preds, average='weighted', zero_division=0)
    else:
        precision, recall, f1 = 0, 0, 0

    # Update history
    history['train_loss'].append(total_loss / len(dataloader))
    history['train_cls_loss'].append(cls_loss_total / len(dataloader))
    history['train_bbox_loss'].append(bbox_loss_total / len(dataloader))
    history['train_accuracy'].append(acc)
    history['train_precision'].append(precision)
    history['train_recall'].append(recall)
    history['train_f1'].append(f1)
    history['epoch_time'].append(epoch_time)

    print(f"Epoch {epoch+1} - Train: Loss={total_loss/len(dataloader):.4f}, Acc={acc:.4f}, Prec={precision:.4f}, Rec={recall:.4f}, F1={f1:.4f}, Time={epoch_time:.2f}s")

    return total_loss / len(dataloader), acc, precision, recall, f1

def validate_model(model, dataloader, criterion_cls, criterion_bbox, device, epoch, history):
    model.eval()
    total_loss = 0
    cls_loss_total = 0
    bbox_loss_total = 0
    correct, total = 0, 0

    all_preds = []
    all_labels = []
    all_scores = []  # For ROC AUC calculation

    with torch.no_grad():
        for images, targets, _ in dataloader:
            batch_loss = 0
            batch_cls_loss = 0
            batch_bbox_loss = 0
            batch_correct = 0

            for i in range(len(images)):
                image = images[i].unsqueeze(0).to(device)
                target = targets[i]

                # Skip images with no annotations
                if len(target['labels']) == 0:
                    continue

                labels = target['labels'].to(device)
                boxes = target['boxes'].to(device)

                # Use the first object for simplicity
                label = labels[0]
                box = boxes[0]

                class_logits, bbox_preds = model(image)

                loss_cls = criterion_cls(class_logits, label.unsqueeze(0))
                loss_bbox = criterion_bbox(bbox_preds, box.unsqueeze(0))
                loss = loss_cls + loss_bbox

                _, pred = torch.max(class_logits, 1)

                # Store for metrics calculation
                all_preds.append(pred.item())
                all_labels.append(label.item())
                all_scores.append(torch.softmax(class_logits, dim=1)[0][1].item())  # Probability of class 1 (Boulder)

                batch_correct += (pred == label.unsqueeze(0)).sum().item()
                batch_loss += loss.item()
                batch_cls_loss += loss_cls.item()
                batch_bbox_loss += loss_bbox.item()

            total_loss += batch_loss / len(images)
            cls_loss_total += batch_cls_loss / len(images)
            bbox_loss_total += batch_bbox_loss / len(images)
            correct += batch_correct
            total += len(images)

    # Calculate metrics
    acc = correct / total if total > 0 else 0

    if len(all_preds) > 0 and len(all_labels) > 0:
        all_preds = np.array(all_preds)
        all_labels = np.array(all_labels)
        all_scores = np.array(all_scores)

        precision, recall, f1, _ = precision_recall_fscore_support(all_labels, all_preds, average='weighted', zero_division=0)

        # Calculate ROC AUC if we have both classes
        if len(np.unique(all_labels)) > 1:
            auc = roc_auc_score(all_labels, all_scores)
        else:
            auc = 0
    else:
        precision, recall, f1, auc = 0, 0, 0, 0

    # Update history
    history['val_loss'].append(total_loss / len(dataloader))
    history['val_cls_loss'].append(cls_loss_total / len(dataloader))
    history['val_bbox_loss'].append(bbox_loss_total / len(dataloader))
    history['val_accuracy'].append(acc)
    history['val_precision'].append(precision)
    history['val_recall'].append(recall)
    history['val_f1'].append(f1)
    history['val_auc'].append(auc)

    print(f"Epoch {epoch+1} - Val: Loss={total_loss/len(dataloader):.4f}, Acc={acc:.4f}, Prec={precision:.4f}, Rec={recall:.4f}, F1={f1:.4f}, AUC={auc:.4f}")

    return total_loss / len(dataloader), acc, precision, recall, f1, auc

def save_history_to_csv(history, filename):
    """Save training history to a CSV file"""
    with open(filename, 'w', newline='') as csvfile:
        writer = csv.writer(csvfile)
        # Write header
        writer.writerow(['epoch'] + list(history.keys()))
        # Write data for each epoch
        for i in range(len(history['train_loss'])):
            row = [i+1] + [history[key][i] for key in history.keys()]
            writer.writerow(row)
    print(f"History saved to {filename}")


def evaluate_model(model, test_loader, device, iou_threshold=0.5, conf_threshold=0.5, sample_size=None):
    """
    Evaluate the model on test data
    sample_size: if provided, only evaluate on this many batches (for quick training accuracy estimation)
    """
    model.eval()

    all_metrics = {
        'true_positives': 0,
        'false_positives': 0,
        'false_negatives': 0,
        'per_class': {}
    }

    # Use only a subset of data if sample_size is specified
    if sample_size is not None:
        data_iterator = list(itertools.islice(test_loader, sample_size))
        print(f"Evaluating on {len(data_iterator)} batches...")
    else:
        data_iterator = test_loader
        print("Evaluating on full dataset...")

    for images, targets in tqdm(data_iterator):
        images = list(img.to(device) for img in images)
        targets = [{k: v.to('cpu') for k, v in t.items()} for t in targets]

        # Get predictions
        with torch.no_grad():
            predictions = model(images)

        # Process each prediction
        for pred, target in zip(predictions, targets):
            # Apply confidence threshold
            keep = pred['scores'] >= conf_threshold
            pred_boxes = pred['boxes'][keep].cpu()
            pred_labels = pred['labels'][keep].cpu()

            true_boxes = target['boxes']
            true_labels = target['labels']

            # Skip if no boxes to compare
            if len(pred_boxes) == 0 and len(true_boxes) == 0:
                continue

            # All predictions are false positives if no true boxes
            if len(true_boxes) == 0:
                all_metrics['false_positives'] += len(pred_boxes)

                # Track per-class metrics
                for pred_label in pred_labels:
                    label_id = pred_label.item()
                    if label_id not in all_metrics['per_class']:
                        all_metrics['per_class'][label_id] = {'TP': 0, 'FP': 0, 'FN': 0}
                    all_metrics['per_class'][label_id]['FP'] += 1

                continue

            # All true boxes are false negatives if no predictions
            if len(pred_boxes) == 0:
                all_metrics['false_negatives'] += len(true_boxes)

                # Track per-class metrics
                for true_label in true_labels:
                    label_id = true_label.item()
                    if label_id not in all_metrics['per_class']:
                        all_metrics['per_class'][label_id] = {'TP': 0, 'FP': 0, 'FN': 0}
                    all_metrics['per_class'][label_id]['FN'] += 1

                continue

            # Calculate IoU between predictions and ground truth
            ious = box_iou(pred_boxes, true_boxes)

            # Track which ground truths have been matched
            gt_matched = torch.zeros(len(true_boxes))

            # For each prediction, find the best match
            for pred_idx in range(len(pred_boxes)):
                pred_label = pred_labels[pred_idx].item()

                # Initialize per-class metrics if needed
                if pred_label not in all_metrics['per_class']:
                    all_metrics['per_class'][pred_label] = {'TP': 0, 'FP': 0, 'FN': 0}

                # Find best matching ground truth
                best_iou, best_gt_idx = torch.max(ious[pred_idx], dim=0)

                if best_iou >= iou_threshold and gt_matched[best_gt_idx] == 0:
                    # Check if labels match
                    if pred_label == true_labels[best_gt_idx].item():
                        # True positive
                        all_metrics['true_positives'] += 1
                        all_metrics['per_class'][pred_label]['TP'] += 1
                        gt_matched[best_gt_idx] = 1
                    else:
                        # False positive (wrong class)
                        all_metrics['false_positives'] += 1
                        all_metrics['per_class'][pred_label]['FP'] += 1
                else:
                    # False positive (no match or already matched)
                    all_metrics['false_positives'] += 1
                    all_metrics['per_class'][pred_label]['FP'] += 1

            # Find unmatched ground truths (false negatives)
            for gt_idx in range(len(true_boxes)):
                if gt_matched[gt_idx] == 0:
                    gt_label = true_labels[gt_idx].item()

                    # Initialize per-class metrics if needed
                    if gt_label not in all_metrics['per_class']:
                        all_metrics['per_class'][gt_label] = {'TP': 0, 'FP': 0, 'FN': 0}

                    all_metrics['false_negatives'] += 1
                    all_metrics['per_class'][gt_label]['FN'] += 1

    # Calculate overall metrics
    tp = all_metrics['true_positives']
    fp = all_metrics['false_positives']
    fn = all_metrics['false_negatives']

    precision = tp / (tp + fp) if (tp + fp) > 0 else 0
    recall = tp / (tp + fn) if (tp + fn) > 0 else 0
    f1 = 2 * precision * recall / (precision + recall) if (precision + recall) > 0 else 0
    accuracy = tp / (tp + fp + fn) if (tp + fp + fn) > 0 else 0

    # Calculate per-class metrics
    per_class_metrics = {}
    for cls_id, metrics in all_metrics['per_class'].items():
        cls_tp = metrics['TP']
        cls_fp = metrics['FP']
        cls_fn = metrics['FN']

        cls_precision = cls_tp / (cls_tp + cls_fp) if (cls_tp + cls_fp) > 0 else 0
        cls_recall = cls_tp / (cls_tp + cls_fn) if (cls_tp + cls_fn) > 0 else 0
        cls_f1 = 2 * cls_precision * cls_recall / (cls_precision + cls_recall) if (cls_precision + cls_recall) > 0 else 0

        per_class_metrics[cls_id] = {
            'precision': cls_precision,
            'recall': cls_recall,
            'f1': cls_f1,
            'TP': cls_tp,
            'FP': cls_fp,
            'FN': cls_fn
        }

    # Return all metrics
    return {
        'accuracy': accuracy,
        'precision': precision,
        'recall': recall,
        'f1': f1,
        'per_class': per_class_metrics,
        'raw_counts': {
            'TP': tp,
            'FP': fp,
            'FN': fn
        }
    }


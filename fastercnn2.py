class CraterBoulderDataset(Dataset):
    def __init__(self, annotations, img_dir, transforms=None):
        self.img_dir = img_dir
        self.transforms = transforms
        self.annotations = annotations
        self.image_files = list(self.annotations['filename'].unique())

    def __getitem__(self, idx):
        img_name = self.image_files[idx]
        img_path = os.path.join(self.img_dir, img_name)
        img = Image.open(img_path).convert("RGB")

        records = self.annotations[self.annotations['filename'] == img_name]
        boxes = records[['xmin', 'ymin', 'xmax', 'ymax']].values
        boxes = torch.as_tensor(boxes, dtype=torch.float32)

        labels = records['class'].astype('category').cat.codes + 1  # start labels from 1
        labels = torch.as_tensor(labels.values, dtype=torch.int64)

        target = {
            'boxes': boxes,
            'labels': labels,
            'image_id': torch.tensor([idx])
        }

        if self.transforms:
            img = self.transforms(img)

        return img, target

    def __len__(self):
        return len(self.image_files)

